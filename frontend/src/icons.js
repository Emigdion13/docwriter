/**
 * The icon that stands for a space: a robot for AI-Notes, a page for Plain,
 * an open or closed lock for a vault.
 */
export function spaceIcon(space) {
  if (space?.id === 'ai') return 'bot';
  if (space?.kind === 'plain') return 'file';
  return space?.locked ? 'lock' : 'unlock';
}

/**
 * Returns an inline SVG string for the requested icon name.
 * @param {string} name - Name of icon in ICONS
 * @param {number} size - Dimension in pixels (width and height)
 * @param {string} className - Additional CSS classes
 * @returns {string} SVG HTML string
 */
export function icon(name, size = 18, className = '') {
  const content = ICONS[name] || ICONS.file;
  const cls = className ? `i ${className}` : 'i';
  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${content}</svg>`;
}
